/** Code point the table substitutes for anything it does not cover. */
const REPLACEMENT = '?'.charCodeAt(0);

/**
 * Byte offset of a code point's five columns in {@link GLYPHS}.
 *
 * Anything outside 32–126 becomes `?`, so a stray character renders as a mark
 * rather than as a blank — a blank would read as intentional spacing and hide
 * the fact that a string was not what the author thought.
 */
export function glyphColumns(codePoint: number): number {
  const c = codePoint < FIRST_CHAR || codePoint > LAST_CHAR ? REPLACEMENT : codePoint;
  return (c - FIRST_CHAR) * GLYPH_WIDTH;
}

/** Is column `col`, row `row` of the glyph at `offset` set? */
export function glyphPixel(offset: number, col: number, row: number): boolean {
  return ((GLYPHS[offset + col]! >> row) & 1) === 1;
}

/** Width in pixels of `text` at scale 1, including the trailing spacing column. */
export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * GLYPH_ADVANCE - 1) * scale;
}

/** Height in pixels of one line at `scale`. */
export function textHeight(scale = 1): number {
  return GLYPH_HEIGHT * scale;
}

/**
 * Every code point in `text` that this font cannot draw.
 *
 * The title block calls it and refuses rather than silently substituting: a `°`
 * that turns into `?` on the map is a defect that reaches the user as confusion
 * about the number beside it, and the fix — writing `deg` — is free at the point
 * the string is composed and impossible afterwards.
 */
export function unprintable(text: string): string[] {
  const bad: string[] = [];
  for (const ch of text) {
    const code = ch.codePointAt(0)!;
    if (code < FIRST_CHAR || code > LAST_CHAR) {
      bad.push(ch);
    }
  }
  return bad;
}

/** @throws naming the characters, if `text` contains anything the font cannot draw. */
export function assertPrintable(text: string, what: string): void {
  const bad = unprintable(text);
  if (bad.length > 0) {
    throw new Error(
      `${what} contains ${String(bad.length)} character(s) the 5x7 font cannot draw: ` +
        `${bad.map((c) => JSON.stringify(c)).join(', ')}. ` +
        'Title-block text is ASCII 32-126 — write "deg" for a degree sign and "+/-" for a sign.',
    );
  }
}

/** How many glyphs the table holds. For the test that asserts the table is complete. */
export const GLYPH_COUNT = LAST_CHAR - FIRST_CHAR + 1;

/** Total bytes the table should hold, if it covers every glyph. */
export const GLYPH_TABLE_BYTES = GLYPH_COUNT * GLYPH_WIDTH;

/** The table's real length, so a test can compare it to {@link GLYPH_TABLE_BYTES}. */
export function glyphTableBytes(): number {
  return GLYPHS.length;
}
