/**
 * A 5×7 bitmap font, because there is no canvas here.
 *
 * ## Why a font table rather than a canvas
 *
 * R26 puts the export client-side, so `OffscreenCanvas.fillText` is available in
 * the browser — and it is available *only* there. The title block is R25 content
 * and the repo's standing rule is that content whose only route to a check is a
 * screenshot is content nobody checks. WP12 split `panelText.ts` from
 * `controlPanel.ts` for exactly this reason; this is the same split one layer
 * down, and it buys more here, because a canvas would also make the rendered
 * title block depend on which fonts the machine has installed. Two machines
 * exporting the same world would produce two different files.
 *
 * So: a table, five bytes a glyph, rendered by integer blitting. Deterministic,
 * dependency-free, testable in Node, and identical on every platform — which is
 * the property this whole repository is about.
 *
 * ## The encoding
 *
 * Each glyph is five **columns**, left to right. Each column is one byte whose
 * bit `r` is the pixel in row `r`, top row first, so only the low seven bits are
 * used. This is the classic 5×7 LCD layout and it is worth keeping rather than
 * inventing one, because the shapes are known-good and a hand-drawn `S` is not.
 *
 * ASCII 32–126 only. {@link glyphColumns} falls back to `?` for anything else,
 * and {@link assertPrintable} exists so the title block can refuse a non-ASCII
 * string up front rather than render it as a row of question marks — which is
 * why the title block writes `+/-` and `deg` rather than `±` and `°`.
 */

/** Glyph width in pixels, before {@link GLYPH_ADVANCE}'s spacing column. */
export const GLYPH_WIDTH = 5;
/** Glyph height in pixels. */
export const GLYPH_HEIGHT = 7;
/** Horizontal advance per character: the glyph plus one blank column. */
export const GLYPH_ADVANCE = GLYPH_WIDTH + 1;
/** Vertical advance per line: the glyph plus two blank rows. */
export const LINE_ADVANCE = GLYPH_HEIGHT + 2;

/** First and last code points the table covers. */
const FIRST_CHAR = 0x20;
const LAST_CHAR = 0x7e;

